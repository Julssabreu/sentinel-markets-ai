const { contextBridge } = require('electron');
contextBridge.exposeInMainWorld('sentinel', {
  platform: process.platform,
  version: '0.2.0',
  getMarketSnapshot: () => require('electron').ipcRenderer.invoke('market:snapshot'),
  getMacroSnapshot: () => require('electron').ipcRenderer.invoke('macro:snapshot'),
  getNewsSnapshot: () => require('electron').ipcRenderer.invoke('news:snapshot'),
  getEvidenceLedgerStatus: () => require('electron').ipcRenderer.invoke('data:ledger-status'),
  getInstitutionalFactors: () => require('electron').ipcRenderer.invoke('institutional:factors'),
  listAlerts: () => require('electron').ipcRenderer.invoke('alerts:list'),
  upsertAlerts: alerts => require('electron').ipcRenderer.invoke('alerts:upsert', alerts),
  acknowledgeAlert: id => require('electron').ipcRenderer.invoke('alerts:acknowledge', id),
  startCryptoFlow: symbol => require('electron').ipcRenderer.invoke('crypto:flow-start', symbol),
  stopCryptoFlow: symbol => require('electron').ipcRenderer.invoke('crypto:flow-stop', symbol),
  getCryptoFlowSnapshot: symbol => require('electron').ipcRenderer.invoke('crypto:flow-snapshot', symbol),
  onCryptoFlowUpdate: callback => { const listener=(_event,value)=>callback(value);require('electron').ipcRenderer.on('crypto:flow-update',listener);return()=>require('electron').ipcRenderer.removeListener('crypto:flow-update',listener) },
  listAnalysisHistory: () => require('electron').ipcRenderer.invoke('history:list'),
  saveAnalysisHistory: record => require('electron').ipcRenderer.invoke('history:append', record),
  evaluateAnalysisHistory: () => require('electron').ipcRenderer.invoke('history:evaluate'),
  getAtomicMt5: () => require('electron').ipcRenderer.invoke('atomic:mt5'),
  getAtomicTerminals: () => require('electron').ipcRenderer.invoke('atomic:terminals'),
  installAtomicReader: terminalId => require('electron').ipcRenderer.invoke('atomic:install-reader', terminalId),
  getMt5Status: () => require('electron').ipcRenderer.invoke('mt5:status'),
  getMt5Portfolio: () => require('electron').ipcRenderer.invoke('mt5:portfolio'),
  getMt5Factors: () => require('electron').ipcRenderer.invoke('mt5:factors'),
  getMt5Microstructure: symbol => require('electron').ipcRenderer.invoke('mt5:microstructure', symbol),
  searchMt5Symbols: (search, limit) => require('electron').ipcRenderer.invoke('mt5:catalog', search, limit),
  getMt5Rates: (symbol, timeframe, count) => require('electron').ipcRenderer.invoke('mt5:rates', symbol, timeframe, count),
  getMt5MultiRates: (symbol, timeframes, count) => require('electron').ipcRenderer.invoke('mt5:multi-rates', symbol, timeframes, count),
  scanMt5Market: limit => require('electron').ipcRenderer.invoke('mt5:scan', limit)
});
